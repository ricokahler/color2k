import guard from './guard';
import ColorError from './ColorError';

/**
 * Parses a color into red, green, blue, and alpha channel values.
 *
 * Supports hex, RGB, RGBA, HSL, HSLA, CSS named colors, and `transparent`.
 *
 * ```js
 * parseToRgba('rgba(255, 0, 0, 0.5)'); // [255, 0, 0, 0.5]
 * ```
 *
 * @param color The input color.
 * @returns A tuple of red, green, blue, and alpha channel values.
 */
function parseToRgba(color: string): [number, number, number, number] {
  if (typeof color !== 'string') throw new ColorError(color);
  if (color.trim().toLowerCase() === 'transparent') return [0, 0, 0, 0];

  if (namedColorRegex.test(color)) {
    // named colors: hash the name, then walk `colorMap` (see below)
    let hash = 47;
    let i = color.length;
    while (i) hash = (((hash * 65) ^ color.charCodeAt(--i)) | 32) % 2476;
    for (; (hash -= (colorMap.charCodeAt(i) % 95) - 1) > 0; i += 5);
    if (hash === 0) {
      return [
        ...[1, 2, 3].map(
          (j) =>
            (168 -
              (colorMap.charCodeAt(i + j) % 95) +
              ((colorMap.charCodeAt(i + 4) % 95) >> (6 - 2 * j)) * 64) &
            255
        ),
        1,
      ] as [number, number, number, number];
    }
  }

  const reducedHexMatch = reducedHexRegex.exec(color);
  if (reducedHexMatch) {
    const arr = Array.from(reducedHexMatch).slice(1);
    return [
      ...arr.slice(0, 3).map((x) => parseInt(r(x, 2), 16)),
      parseInt(r(arr[3] || 'f', 2), 16) / 255,
    ] as [number, number, number, number];
  }

  const hexMatch = hexRegex.exec(color);
  if (hexMatch) {
    const arr = Array.from(hexMatch).slice(1);
    return [
      ...arr.slice(0, 3).map((x) => parseInt(x, 16)),
      parseInt(arr[3] || 'ff', 16) / 255,
    ] as [number, number, number, number];
  }

  const rgbaMatch = rgbaRegex.exec(color);
  if (rgbaMatch) {
    const arr = Array.from(rgbaMatch).slice(1);
    return [
      ...arr.slice(0, 3).map((x) => parseInt(x, 10)),
      parseFloat(arr[3] || '1'),
    ] as [number, number, number, number];
  }

  const hslaMatch = hslaRegex.exec(color);
  if (hslaMatch) {
    const [h, s, l, a] = Array.from(hslaMatch).slice(1).map(parseFloat);
    if (guard(0, 100, s) !== s) throw new ColorError(color);
    if (guard(0, 100, l) !== l) throw new ColorError(color);
    return [...hslToRgb(h, s, l), Number.isNaN(a) ? 1 : a] as [
      number,
      number,
      number,
      number
    ];
  }

  throw new ColorError(color);
}

/**
 * The CSS named colors, generated by `scripts/color-map.js`.
 *
 * Each color is 5 characters and each character holds `charCode % 95`:
 *
 * 1. the gap between this color's name hash and the previous one, plus 1
 *    (colors are sorted by hash so the lookup above subtracts gaps from the
 *    hash until it reaches zero or less)
 * 2. to 4. the low 6 bits of `168 - channel` for red, green, and blue
 * 5. the 2 bits per channel that step 2 loses
 *
 * A name that is not a color is rejected unless its hash happens to match one
 * of the 148 stored hashes (roughly a 6% chance).
 */
